// Writes supabase/veri/3-modeller-vitrin.sql: the showcase models (Chester, modern, İskandinav, blok, puflar)
// (lib/seed/showcase-models.ts) for the Supabase SQL editor. Safe to run twice.
//
//   npx tsx scripts/build-showcase-sql.ts

import { writeFileSync } from "node:fs";
import path from "node:path";
import { RETIRED_SHOWCASE_SLUGS, SHOWCASE_MODELS } from "../lib/seed/showcase-models";

const q = (v: string | number | boolean | null | undefined): string =>
  v === null || v === undefined ? "null" : typeof v === "string" ? `'${v.replace(/'/g, "''")}'` : String(v);

const rows = SHOWCASE_MODELS.map((m) => {
  if (m.source.kind !== "parametric") throw new Error(m.slug);
  return `  (${[m.slug, m.name, JSON.stringify(m.source.params), m.fabricMaterialNames.join(","), m.dimensionsCm.w, m.dimensionsCm.d, m.dimensionsCm.h, m.defaultFabricCode, m.isActive, m.sortOrder].map(q).join(", ")})`;
});

const sql = `-- ORMEN Atelier: showcase models (Chester, modern, İskandinav, blok, puflar). GENERATED by scripts/build-showcase-sql.ts; do not edit by hand.
-- Paste into the Supabase SQL editor and press Run. Run supabase/veri/2-kumaslar-misso.sql first (default fabrics).
-- Running it again is safe: missing models are added; existing ones keep their shape and name
-- (they may have been edited in the panel) and only get this version's order and default fabric.
-- Models taken off the showcase are switched off (not deleted: can be switched back on in the panel).

update public.models set is_active = false where firm_id is null and slug in (${RETIRED_SHOWCASE_SLUGS.map(q).join(", ")});

update public.models m set default_fabric_code = v.fabric, sort_order = v.sort_order
from (values
${SHOWCASE_MODELS.map((m) => `  (${[m.slug, m.defaultFabricCode, m.sortOrder].map(q).join(", ")})`).join(",\n")}
) as v (slug, fabric, sort_order)
where m.firm_id is null and m.slug = v.slug;

insert into public.models (firm_id, slug, name, procedural_key, params, fabric_material_names, width_cm, depth_cm, height_cm, default_fabric_code, is_active, sort_order)
select null, v.slug, v.name, 'parametric', v.params::jsonb, string_to_array(v.materials, ','), v.w, v.d, v.h, v.fabric, v.active, v.sort_order
from (values
${rows.join(",\n")}
) as v (slug, name, params, materials, w, d, h, fabric, active, sort_order)
where not exists (select 1 from public.models m where m.firm_id is null and m.slug = v.slug);
`;
const out = path.join(process.cwd(), "supabase", "veri", "3-modeller-vitrin.sql");
writeFileSync(out, sql);
console.log(`${out}: ${SHOWCASE_MODELS.length} model`);
